/** Every `<path d>` in the icon's SVG, joined. The frame rect is not a path. */
function pathOf(weight, slug) {
  const file = join(ASSETS, weight, weight === "regular" ? `${slug}.svg` : `${slug}-${weight}.svg`);
  let svg;
  try {
    svg = readFileSync(file, "utf8");
  } catch {
    throw new Error(`no ${weight} icon named "${slug}" in @phosphor-icons/core ${VERSION}`);
  }
  const paths = [...svg.matchAll(/<path\s[^>]*?\bd="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) throw new Error(`${slug} (${weight}) has no path`);
  return paths.join(" ");
}

function table(name, type, weight, map) {
  const rows = Object.entries(map)
    .map(([key, slug]) => `  "${key}": "${pathOf(weight, slug)}", // ${slug}`)
    .join("\n");
  return `export const ${name}: Record<${type}, string> = {\n${rows}\n};\n`;
}

